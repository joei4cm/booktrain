def preset_label(key: str) -> str:
    """领域 → 中文名（未知领域原样返回）。"""
    return DOMAIN_PRESETS.get(key, (key, ""))[0]


def preset_text(key: str) -> str:
    """领域 → 预设文本（未知领域返回空串）。"""
    return DOMAIN_PRESETS.get(key, ("", ""))[1]


def available_domains() -> list[tuple[str, str]]:
    """所有可用领域（key, 中文名）。"""
    return [(k, v[0]) for k, v in DOMAIN_PRESETS.items()]
